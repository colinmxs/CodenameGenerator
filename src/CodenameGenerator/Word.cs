namespace CodenameGenerator
{
    /// <summary>
    /// The category of word a <see cref="WordBank"/> supplies.
    /// </summary>
    public enum Word
    {
        /// <summary>A noun, e.g. "arthropod".</summary>
        Noun,

        /// <summary>An adjective, e.g. "rambunctious".</summary>
        Adjective,

        /// <summary>An adverb, e.g. "laboriously".</summary>
        Adverb,

        /// <summary>A verb, e.g. "lobotomize".</summary>
        Verb,

        /// <summary>A first name of any gender, e.g. "David".</summary>
        FirstName,

        /// <summary>A last name, e.g. "Jones".</summary>
        LastName,

        /// <summary>A title of any gender, e.g. "President".</summary>
        Title,

        /// <summary>A day of the week, e.g. "Tuesday".</summary>
        Day,

        /// <summary>A female first name, e.g. "Ada".</summary>
        FemaleFirstName,

        /// <summary>A male first name, e.g. "Grace" is not one, "Alan" is.</summary>
        MaleFirstName,

        /// <summary>A month of the year, e.g. "April".</summary>
        Month,

        /// <summary>A U.S. state name, e.g. "Idaho".</summary>
        StateName,

        /// <summary>A male title, e.g. "Sir".</summary>
        MaleTitle,

        /// <summary>A female title, e.g. "Madam".</summary>
        FemaleTitle,

        /// <summary>An occupation, e.g. "Airline Traffic Controller".</summary>
        JobTitle,

        /// <summary>A country, e.g. "Albania".</summary>
        Country,

        /// <summary>A city, e.g. "New York".</summary>
        City,
    }
}
